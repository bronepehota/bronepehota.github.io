#!/usr/bin/env node
/**
 * Generate build-info.ts with version and deployment date
 * This script is called during build to inject build metadata
 */

const fs = require('fs');
const path = require('path');

// Get build date - either from env or use current date
const buildDate = process.env.BUILD_DATE || new Date().toISOString();
const buildTimestamp = new Date(buildDate).getTime();
const dateObj = new Date(buildDate);

// Auto-generate version in format YY.M.PATCH (e.g., 26.2.1)
// Year (2 digits), month (1-12), patch (from env or 0)
const year = String(dateObj.getFullYear()).slice(-2); // 26 for 2026
const month = dateObj.getMonth() + 1; // 1-12
const patch = process.env.BUILD_PATCH || '0';
const version = `${year}.${month}.${patch}`;

// Get git commit SHA if available
const gitSha = (process.env.GITHUB_SHA || 'dev').slice(0, 7);

// Format date for display (Russian locale)
const displayDate = dateObj.toLocaleDateString('ru-RU', {
  year: 'numeric',
  month: '2-digit',
  day: '2-digit',
}).replace(/\//g, '.');

// Format time for display
const displayTime = dateObj.toLocaleTimeString('ru-RU', {
  hour: '2-digit',
  minute: '2-digit',
  timeZoneName: 'short',
});

const buildInfo = {
  version,
  buildDate,
  buildTimestamp,
  displayDate,
  displayTime,
  gitSha,
  isProduction: process.env.NODE_ENV === 'production',
};

// Generate TypeScript file
const outputContent = `// Auto-generated by scripts/generate-build-info.js
// DO NOT EDIT MANUALLY

export const BUILD_INFO = ${JSON.stringify(buildInfo, null, 2)} as const;

export type BuildInfo = typeof BUILD_INFO;
`;

// Write to src/lib/build-info.ts
const outputPath = path.resolve(__dirname, '../src/lib/build-info.ts');
fs.writeFileSync(outputPath, outputContent, 'utf-8');

console.log(`✓ Build info generated: v${version} (${displayDate} ${displayTime})`);
console.log(`  Git SHA: ${gitSha}`);
